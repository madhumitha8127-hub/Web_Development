// FOR LOOP
console.log("For Loop:");

for (let i = 1; i <= 5; i++) {
    console.log(i);
}


// WHILE LOOP
console.log("While Loop:");

let j = 1;

while (j <= 5) {
    console.log(j);
    j++;
}


// DO...WHILE LOOP
console.log("Do While Loop:");

let k = 1;

do {
    console.log(k);
    k++;
} while (k <= 5);